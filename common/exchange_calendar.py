"""거래소 휴장일·조기 마감 (지수 본장용)

미국(NYSE/나스닥 현물): 공식 발표 휴장일과 조기 마감(뉴욕 13:00) 2022~2027
독일(Xetra): 새해, 성금요일, 부활절 월요일, 5월 1일, 12월 24·25·26·31일 휴장
CFD는 휴장일에도 시세가 있지만 본장이 없으므로 본장 전략은 쉼
"""
from datetime import date, time

from dateutil.easter import easter

US_HOLIDAYS = {date.fromisoformat(x) for x in (
    "2022-01-17 2022-02-21 2022-04-15 2022-05-30 2022-06-20 2022-07-04 2022-09-05 2022-11-24 2022-12-26 "
    "2023-01-02 2023-01-16 2023-02-20 2023-04-07 2023-05-29 2023-06-19 2023-07-04 2023-09-04 2023-11-23 2023-12-25 "
    "2024-01-01 2024-01-15 2024-02-19 2024-03-29 2024-05-27 2024-06-19 2024-07-04 2024-09-02 2024-11-28 2024-12-25 "
    "2025-01-01 2025-01-09 2025-01-20 2025-02-17 2025-04-18 2025-05-26 2025-06-19 2025-07-04 2025-09-01 2025-11-27 2025-12-25 "
    "2026-01-01 2026-01-19 2026-02-16 2026-04-03 2026-05-25 2026-06-19 2026-07-03 2026-09-07 2026-11-26 2026-12-25 "
    "2027-01-01 2027-01-18 2027-02-15 2027-03-26 2027-05-31 2027-06-18 2027-07-05 2027-09-06 2027-11-25 2027-12-24").split()}
US_EARLY = {date.fromisoformat(x) for x in (
    "2022-11-25 2023-07-03 2023-11-24 2024-07-03 2024-11-29 2024-12-24 2025-07-03 2025-11-28 2025-12-24 "
    "2026-11-27 2026-12-24 2027-11-26").split()}
US_EARLY_CLOSE = time(13, 0)


def us_closed(d):
    return d.weekday() >= 5 or d in US_HOLIDAYS


def us_close_time(d, normal=time(16, 0)):
    return US_EARLY_CLOSE if d in US_EARLY else normal


def de_closed(d):
    e = easter(d.year)
    fixed = {(1, 1), (5, 1), (12, 24), (12, 25), (12, 26), (12, 31)}
    return d.weekday() >= 5 or (d.month, d.day) in fixed or (d - e).days in (-2, 1)
